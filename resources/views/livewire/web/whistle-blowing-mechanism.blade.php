                            <p>Sui Southern Gas Company Limited (SSGC) is committed to maintaining high standards of
                                integrity, accountability, transparency and ethical conduct. The Company has established
                                a formal, independent, confidential and transparent mechanism for reporting suspected
                                unethical, illegal, fraudulent, unsafe or improper conduct relating to SSGC.</p>
                            <p>The Whistle Blowing Mechanism is intended to facilitate the timely identification and
                                mitigation of governance, financial, operational, regulatory, safety and cybersecurity
                                risks.</p>
                            <h5>Who Can Report?</h5>
                            <p>Any person may submit a whistleblower complaint where the matter relates to SSGC, its
                                business, operations, governance, employees, contractors, service providers, assets or
                                stakeholders.</p>
                            <p>This includes:</p>
                            <ul>
                                <li class="li-1">Employees, including permanent, contractual, temporary, deputed, trainee and
                                    outsourced employees;
                                </li>
                                <li class="li-1">Directors and consultants;</li>
                                <li class="li-1">Contractors, suppliers, vendors and service providers;</li>
                                <li class="li-1">Customers and other external stakeholders; and</li>
                                <li class="li-1">Any other person having reasonable grounds to report misconduct relating to SSGC.
                                </li>
                            </ul>
                            <h5 class="mt-5">What Can Be Reported?</h5>
                            <p>Concerns may be reported regarding, but not limited to:</p>
                            <ul>
                                <li class="li-1">Fraud or attempted fraud;</li>
                                <li class="li-1">Misappropriation or theft of Company assets or funds;</li>
                                <li class="li-1">Forgery or falsification of records;</li>
                                <li class="li-1">Bribery, kickbacks, corruption or illegal gratification;</li>
                                <li class="li-1">Conflict of interest;</li>
                                <li class="li-1">Abuse or misuse of authority;</li>
                                <li class="li-1">Favoritism or collusive practices;</li>
                                <li class="li-1">Unauthorized influence in procurement, contracting or recruitment;</li>
                                <li class="li-1">Violation of applicable laws, rules, regulations or Company policies;</li>
                                <li class="li-1">Serious regulatory or legal non-compliance;</li>
                                <li class="li-1">Serious negligence or misconduct;</li>
                                <li class="li-1">Gross misuse or waste of Company resources;</li>
                                <li class="li-1">Improper procurement or contract management practices;</li>
                                <li class="li-1">Deliberate concealment of information;</li>
                                <li class="li-1">Unauthorized disclosure of confidential or sensitive information;</li>
                                <li class="li-1">Conduct endangering health or safety;</li>
                                <li class="li-1">HSE or environmental violations;</li>
                                <li class="li-1">Activities compromising operational integrity or Company security;</li>
                                <li class="li-1">Unauthorized access to systems or data;</li>
                                <li class="li-1">Misuse of Company information systems;</li>
                                <li class="li-1">Manipulation or destruction of electronic records; and</li>
                                <li class="li-1">Cybersecurity breaches or concealment thereof.</li>
                            </ul>
                            <h5 class="mt-5">How to Submit a Whistleblower Complaint</h5>
                            <p>Whistleblower complaints should be submitted directly to the Group Chief Internal Auditor
                                (GCIA) and shall not be routed through Management or any operational department.</p>
                            <p><strong>Dedicated Whistleblower Email:</strong> <a
                                    href="mailto:whistleblower@ssgc.com.pk">whistleblower@ssgc.com.pk</a></p>
                            <p>Complaints may also be submitted by post or hand delivery to:</p>
                            <p>
                                Group Chief Internal Auditor<br>
                                Sui Southern Gas Company Limited<br>
                                SSGC Head Office<br>
                                Karachi
                            </p>
                            <p>A Whistle Blowing Report Form (Annexure-A) is available for download below. However, a
                                complaint shall not be rejected merely because it has not been submitted in the
                                prescribed format.</p>
                            <p>
                                <a href="{{ asset('media/pdfs/SSGC-Whistle-Blowing-Report-Form-Annexure-A.pdf') }}">[Download
                                    Whistle Blowing Report Form – Annexure A]</a></p>
                            <h5>Anonymous Complaints</h5>
                            <p>The Whistle Blowing Policy requires the whistleblower to disclose his/her identity and
                                provide contact details to facilitate communication and further assessment of the
                                complaint.</p>
                            <p>Accordingly, complaints or information submitted without identifying the whistleblower
                                may not be acted upon where:</p>
                            <ul>
                                <li class="li-1">the disclosure does not indicate the identity of the whistleblower;</li>
                                <li class="li-1">the identity of the whistleblower is found to be incorrect or false;</li>
                                <li class="li-1">the identity of the whistleblower cannot be confirmed;</li>
                                <li class="li-1">the whistleblower cannot be contacted; or</li>
                                <li class="li-1">the whistleblower cannot be traced within a reasonable time.</li>
                            </ul>
                            <p>Whistleblowers are therefore encouraged to provide their correct identity and contact
                                details when submitting a complaint.</p>
                            <h5 class="mt-5">Confidentiality and Protection Against Retaliation</h5>
                            <p>SSGC is committed to maintaining the confidentiality of whistleblower complaints. The
                                identity of the whistleblower and information relating to a complaint shall be treated
                                as strictly confidential and disclosed only where required by law or for the purpose of
                                conducting a fair review.</p>
                            <p>SSGC strictly prohibits retaliation, harassment, victimization, discrimination,
                                intimidation or any other adverse action against a whistleblower solely because a
                                whistleblower complaint has been submitted under the Whistle Blowing Policy.</p>
                            <p>Retaliation against a whistleblower constitutes misconduct and may result in disciplinary
                                or other appropriate action.</p>
                            <h5>Matters Not Covered by the Whistle Blowing Mechanism</h5>
                            <p>The Whistle Blowing Mechanism is not intended for:</p>
                            <ul>
                                <li class="li-1">Routine employee grievances;</li>
                                <li class="li-1">Salary disputes, promotions, transfers, appraisals or other Human Resource
                                    matters;
                                </li>
                                <li class="li-1">Personal disputes having no governance or ethical implications;</li>
                                <li class="li-1">Routine customer service complaints dealt with through established Company complaint
                                    mechanisms; or
                                </li>
                                <li class="li-1">Matters already covered under another approved Company policy or grievance
                                    mechanism.
                                </li>
                            </ul>
                            <p>Cases relating exclusively to workplace harassment shall be dealt with under the
                                applicable Harassment Policy unless they also involve reportable conduct covered by this
                                Policy.</p>
                            <h5>False or Malicious Complaints</h5>
                            <p>The Company encourages the reporting of genuine concerns based on reasonable grounds. No
                                adverse action shall be taken against a complainant merely because a complaint is
                                subsequently found to be unsubstantiated.</p>
                            <p>However, knowingly making false, malicious, frivolous or misleading allegations may
                                result in appropriate disciplinary or legal action in accordance with applicable
                                requirements.</p>
                            <h5>Review of Complaints</h5>
                            <p>All whistleblower complaints received will be subject to preliminary assessment in
                                accordance with the Company’s approved Whistle Blowing Policy. Where warranted, a
                                detailed review may be undertaken by Internal Audit.</p>
                            <p>Submission of a complaint does not automatically imply that a detailed review will be
                                initiated or that the allegations will be substantiated. The Company will determine the
                                appropriate course of action based on the nature of the complaint, available information
                                and evidence.</p>
                            <h5>Report a Concern</h5>
                            <p><strong>Confidential Whistleblower Email:</strong><br>
                                <a href="mailto:whistleblower@ssgc.com.pk">whistleblower@ssgc.com.pk</a></p>
                            <p><strong>Postal / Hand Delivery:</strong><br>
                                Group Chief Internal Auditor<br>
                                Sui Southern Gas Company Limited<br>
                                SSGC Head Office, Karachi</p>

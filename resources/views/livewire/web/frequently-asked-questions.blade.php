                            <article class="list"><h3 class="trigger"><span class="faq-marker"></span><a href="#">Q2.
                                        What is the billing cycle/ timeline that the Company follows to bill its
                                        customers? </a></h3>
                                <div class="toggle_container entry-content" style="display: none;">
                                    <div class="block"><p></p>
                                        <p>SSGC has to comply with OGRA directives to serve gas bills based on meter
                                            readings on 30 days basis to the customers therefore SSGC follows a
                                            well-defined billing program to cover 365 days of sale for the year. The
                                            billing program is developed in a way to ensure 12 monthly meter readings
                                            and accordingly issuance of bills, annually. Industrial &amp; Commercial
                                            customers are billed on a calendar month basis and meter reading of customer
                                            is obtained at the last day of each month.</p>
                                        <p></p>
                                    </div>
                                </div>
                            </article>


                            <article class="list"><h3 class="trigger"><span class="faq-marker"></span><a href="#">Q3.
                                        What is provisional billing? </a></h3>
                                <div class="toggle_container entry-content" style="display: none;">
                                    <div class="block"><p></p>
                                        <p>If due to any reason, the meter is not read during a billing cycle,
                                            provisional bills (system generated) are issued. The amount so paid by
                                            virtue of provisional bills is adjusted against the bill raised on the basis
                                            of actual reading during subsequent billing cycle. The remarks on the bill
                                            mention reasons of provisional billing. Customer may contact nearest CFC /
                                            Billing Zone to inquire and for remedial actions. The contact number and
                                            address of the nearest CFC / Billing Zone is mentioned on the gas bills of
                                            the respective areas.</p>
                                        <p></p>

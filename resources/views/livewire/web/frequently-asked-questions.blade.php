                            <article class="list"><h3 class="trigger"><span class="faq-marker"></span><a href="#">Q13.
                                        What is PUG? </a></h3>
                                <div class="toggle_container entry-content" style="display: none;">
                                    <div class="block"><p></p>
                                        <p>In case, the meter, for any reason whatsoever, ceases or omits to register
                                            regularly the volume of natural gas supplied, the meter is said to be
                                            Passing Un-registered Gas (PUG). The company change the meter. Estimated
                                            bill based on new meter consumption is charged for the period meter was
                                            PUG.</p>
                                        <p></p>
                                    </div>
                                </div>
                            </article>



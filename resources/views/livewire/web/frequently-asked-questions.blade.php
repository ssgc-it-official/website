                            <article class="list"><h3 class="trigger"><span class="faq-marker"></span><a href="#">Q9:
                                        What is BTU / MMBTU?</a></h3>
                                <div class="toggle_container entry-content" style="display: none;">
                                    <div class="block"><p></p>
                                        <p>A BTU is defined as amount of heat required to raise the temperature of one 1
                                            pound (0.454 kg) of liquid water by 1 °F (0.556 °C) at a constant pressure
                                            of one atmosphere. When 1 Btu is represented in a unit of million, it is
                                            termed as Metric Million British Thermal Unit (MMBtu). The recorded volume
                                            is measured in terms of cubic feet or cubic meters which is converted to
                                            British Thermal Units (BTUs) based on gas quality showing as GCV in your
                                            bill.</p>
                                        <p>MMBTU = MCF x GCV / 1,000 where MCF (Thousand Cubic Feet) = SCM / 28.17385 or
                                            SCF/10</p>
                                        <p></p>
                                    </div>
                                </div>
                            </article>



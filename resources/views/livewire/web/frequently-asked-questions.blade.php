                            <article class="list"><h3 class="trigger"><span class="faq-marker"></span><a href="#">Q1.
                                        How is the gas consumption of each customer recorded? </a></h3>
                                <div class="toggle_container entry-content" style="display: none;">
                                    <div class="block"><p></p>
                                        <p>The gas meters installed by SSGC, at the premise of the customer, records gas
                                            volume consumed in cubic meter or cubic feet by the customer. The recording
                                            of gas consumption on these meters is done through Digital Handheld Devices.
                                            These monthly reads are recorded and maintained by the company as prima
                                            facie evidence of gas sale.</p>

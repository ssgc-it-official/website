                <h3>Introduction</h3>
                <p>Sui Southern Gas Company Limited (SSGC) requires of its entire staff, both executive staff and
                    subordinate employees, the observance of the highest ethical standards in the conduct of its
                    business activities. The Business Principles and Ethics Policy (BPEP) is intended to assist<br>
                    SSGC staff in meeting the standards of professional and personal integrity expected and required of
                    them. SSGC staff will act with integrity at all times, to protect and safeguard the reputation of
                    the Company. Contravention of the BPEP will be regarded as misconduct.</p>
                <h3>SSGC’s Obligations</h3>
                <p>SSGC will ensure that, through this BPEP, and through other means of communication, its entire staff
                    is aware of the required standards, rules and regulations.</p>
                <h3>Specific Guidelines</h3>
                <p>The followings specific guidelines are prescribed for SSGC staff:</p>
                <h4>1.&nbsp;&nbsp; &nbsp;Conflict of Interest</h4>
                <p>Each staff member has a prime responsibility to the Company and is expected to avoid any activity
                    that could interfere with that responsibility. Staff should not engage in activities or transactions
                    which may give rise to, or which may be seen to be giving rise to, conflict between their personal
                    interests and the interests of the Company. Such conflict could arise in a number of ways and in a
                    number of situations. The following paragraphs outline some specifically forbidden situations. This
                    list is, however, not exhaustive. In case of doubt, the advice of the Management should be
                    sought.</p>
                <p>i. SSGC purchases equipment, material and services for various aspects of its operations. SSGC staff
                    members are forbidden from holding any financial interest, directly or indirectly, in any
                    organization supplying goods or services to the Company:<br>
                    ii. SSGC staff should not participate in any external activity that competes, directly or
                    indirectly, with the Company;<br>
                    iii. SSGC staff should not engage in any outside business or activity that might interfere with
                    their duties and responsibilities to the Company;<br>
                    iv. No staff member should sell, lease or buy equipment, material or services to or from the Company
                    except as may be necessary in the normal course of his/her duties as an employee;<br>
                    v. Staff members are not permitted to conduct personal business activities on the Company’s premises
                    or to use Company facilities for such purpose;<br>
                    vi. If a staff member has direct or indirect interest or family connections with an external
                    organization that has business dealings with SSGC, details of such connections and interest should
                    be fully disclosed to the Management;<br>
                    vii. Staff members should disclose to the Management details in respect of any relationship(s) with
                    other staff members; and<br>
                    viii. Staff members shall not perform any act or get involved in any situation that potentially
                    could conflict with the principles outlined above.</p>
                <h4>2.&nbsp;&nbsp; &nbsp;Confidentiality</h4>
                <p>Staff members should not keep or make copies of correspondence; documents, papers and records,
                    drawings and data (defined as the “Confidential Information”) list of clients or customers without
                    the consent of the Company and all such information should be surrendered to the Company when the
                    individual leaves the Company’s employment and complete record of the same should be maintained
                    thereafter for a period ten (10) years. Confidential information should be kept on Company premises
                    only and unpublished information may be disclosed to external organizations/individual only on “need
                    to know “basis. In case of doubt in this regard, the Management’s advice should be sought.</p>
                <h4>3.&nbsp;&nbsp; &nbsp;Contributions</h4>
                <p>No funds or assets of the Company should be contributed directly or indirectly to; any political
                    party or organization or to any individual who either holds public office or is a candidate for
                    public office. SSGC does not provide political contributions/funds to either groups or associations
                    whose activities promote political interest through trade association. Neither does SSGC permit the
                    attending/holding of political activities/rallies on its premises at any time nor permit its
                    employees to attend the same during office hours.</p>
                <h4>4.&nbsp;&nbsp; &nbsp;Inducement Payments</h4>
                <p>Staff members should not give or receive payments that are intended to influence a business decision
                    or to compromise independent judgment; nor should any staff member receive money for having given
                    Company business to an outside agency. Payment of any nature to government officials to induce them
                    to perform their duties is strictly prohibited.</p>
                <h4>5.&nbsp;&nbsp; &nbsp;Proper Recording of Funds, Assets, Receipts and Disbursements</h4>
                <p>All funds, assets, receipts and disbursements should be properly recorded in the books of the
                    Company. In particular no funds or account should be established or maintained for purposes that are
                    not fully and accurately reflected in the books and records of the Company. Funds and assets
                    received or disbursed should be fully and accurately reflected in the books and the records of the
                    Company. No false or fictitious entries should be made or misleading reports pertaining to the
                    Company or its operations should be issued.</p>
                <h4>6.&nbsp;&nbsp; &nbsp;Loan and/or Credit Facilities Obtained from Financial institution</h4>
                <p>Any loan and/or credit facility obtained on false representation including but not limited to
                    preparing forged financial statements shall be deemed to be a fraudulent act.</p>
                <p>Any default on loan and/or credit facility obtained on the basis of being an employee of SSGC shall
                    be considered as violation of BPEP and will be construed as misconduct on part of the employee.</p>
                <h4>7.&nbsp;&nbsp; &nbsp;Agreements with Agents, Sates Representatives or Consultants</h4>
                <p>Agreements with agents, sales representatives or consultant should state clearly the services to be
                    performed for the Company, the amount to be paid, and all other relevant terms and conditions.
                    Payments and transaction should be supported by documentary evidence.</p>
                <h4>8.&nbsp;&nbsp; &nbsp;Relationships and Dealings with Government Officials, Media, Suppliers,
                    Consultants, Agents, Intermediaries and other Parties</h4>
                <p>SSGC’s relationships and dealings with Government officials, external agencies, parties, and
                    individuals should, at all times, be such that SSGC’s integrity and its reputation would not be
                    damaged if details of the relationship or dealings were to become public knowledge. It is the
                    responsibility of each SSGC staff member to exercise good judgments so as to act in a manner that
                    will reflect favorably on the Company and the individual. Staff member should only make statements
                    to the media, speeches in public forums, or publish articles in newspapers etc. with prior
                    authorization. In a personal capacity also, due care should be taken while discussing the Company’s
                    performance or plans with outsiders. Staff members having questions on how to comply with this
                    requirement should consult with the Management.</p>
                <h4>9.&nbsp;&nbsp; &nbsp;Health, Safety and Environment (HSE) While ensuring HSE policies every staff
                    member will endeavor to achieve:</h4>
                <p>•&nbsp;&nbsp; &nbsp;Continual improvements of the Company’s Health, Safety and Environment management
                    system.<br>
                    •&nbsp;&nbsp; &nbsp;Managing all phases of the Company’s operations in a manner that prevents
                    pollution and minimizes adverse effects on the environment.<br>
                    •&nbsp;&nbsp; &nbsp;Providing safe and healthy work environment for all employees.<br>
                    •&nbsp;&nbsp; &nbsp;Reduction of health, safety and environmental hazards and accidents by applying
                    suitable controls and being prepared for emergency situations.<br>
                    •&nbsp;&nbsp; &nbsp;Adherence to all applicable health, safety environment legislations, standards
                    and guidelines.<br>
                    Staff members should not tamper with or misuse any item provided by the Company to secure the
                    safety, health and welfare of its staff and for the protection of the environment.</p>
                <h4>10.&nbsp;&nbsp; &nbsp;Alcohol, Drugs and Gambling</h4>
                <p>The use of alcohol in any form is prohibited on all Company locations/premises. Similarly, the use of
                    drugs, except under medical advice, is prohibited on all Company locations/premises. Any staff
                    member arriving at a workplace under the influence of alcohol or drugs will not be permitted to
                    enter the premises and will be liable to disciplinary action.</p>
                <p>All forms of gambling/betting on the Company’s premises are forbidden</p>
                <h4>11.&nbsp;&nbsp; &nbsp;Receiving Gifts</h4>
                <p>No staff member shall seek, accept or permit himself/herself or any member of his/her family to
                    accept any gift or favor, the receipt of which will place him/her under any form of official
                    obligation to the donor. As part of building relationship with customers, supplier etc. staff
                    members may receive occasional gifts, provided that the gift is of nominal value (e.g. pens,
                    notepads, calendars, diaries, keychains or such promotional material) and the gift is neither
                    intended nor perceived by others to be intended to improperly influence business decisions.</p>
                <p>Occasionally, there may be times when refusing a substantial gift would be impractical or
                    embarrassing. In those rare instances such gift should be handed over to management for suitable
                    disposal.</p>
                <h4>12.&nbsp;&nbsp; &nbsp;Work Place Harassment</h4>
                <p>SSGC staff will maintain an environment that is free from harassment and in which all employees are
                    equally respected. Workplace harassment is defined as any action that creates an intimidating,
                    hostile or offensive work environment. Such actions include, but are not limited to sexual
                    harassment, disparaging comments based on gender, religion, race or ethnicity.</p>
                <h4>13.&nbsp;&nbsp; &nbsp;Reporting Lines</h4>
                <p>Direct reporting lines for all employees are clear and must be used in all business related matters.
                    However, when an officer reports an adverse matter relating to Company to his next senior officer
                    who does not take any action then the officer has the right to go to the senior Officers.</p>
